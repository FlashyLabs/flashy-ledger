#!/usr/bin/env node
// Emits this repository's front door, and renders it for whichever stack the
// repository runs.
//
// Vendored: byte-identical everywhere, dependency-free, and driven entirely by
// a per-repo `frontdoor.config.json`. Nothing repository-specific belongs in
// this file — the drift test in @flashyos/frontdoor fails if any copy carries
// a domain, an org slug or a lane.
//
//   node scripts/emit-frontdoor.mjs            emit the door file
//   node scripts/emit-frontdoor.mjs --html     also write the HTML partial
//   node scripts/emit-frontdoor.mjs --react    also write the React component
//   node scripts/emit-frontdoor.mjs --check    render to memory, write nothing

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname } from 'node:path'

const NOT_AUTHORITY =
  'A rung buys a reply and a place in a queue. It never buys authority, money, or access. ' +
  'Publishing a file at a domain proves that someone can write to that host — it does not prove ' +
  'an organisation is who it says it is, and this door does not treat it as though it did. ' +
  'Where real authority is needed it is delegated and verified through flashyID, and the chain is checked.'

const CFG = 'frontdoor.config.json'
if (!existsSync(CFG)) {
  console.error(`\n  no ${CFG} — a repository declares its own lanes; this script holds none.\n`)
  process.exit(1)
}
const cfg = JSON.parse(readFileSync(CFG, 'utf8'))
const args = new Set(process.argv.slice(2))
const CHECK = args.has('--check')

const door = {
  frontdoor: '1',
  property: cfg.property,
  org: cfg.org,
  lanes: cfg.lanes,
  rungs: cfg.rungs,
  endpoint: cfg.endpoint,
  ladder: cfg.ladder,
  updated: cfg.updated,
  notAuthority: NOT_AUTHORITY,
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const write = (p, body) => {
  if (CHECK) return
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, body)
}

write(cfg.out ?? 'public/.well-known/frontdoor.json', JSON.stringify(door, null, 2) + '\n')

// ── The HTML partial ────────────────────────────────────────────────────────
// Framework-free. Static generators inline it at build; hand-written sites
// paste it and the drift test catches an edit. No script, no styling opinions
// beyond class names the host site owns.
const lanesHtml = door.lanes.map(l => `      <li class="fd-lane">
        <span class="fd-lane-name">${esc(l.id)}</span>
        ${l.question ? `<span class="fd-lane-q">${esc(l.question)}</span>` : ''}
      </li>`).join('\n')

const htmlPartial = `<!-- Generated by scripts/emit-frontdoor.mjs from ${CFG}. Do not edit. -->
<section class="fd" aria-labelledby="fd-h">
  <h2 class="fd-h" id="fd-h">${esc(cfg.voice ?? 'Reach us')}</h2>
  <ul class="fd-lanes">
${lanesHtml}
  </ul>
  <p class="fd-ladder">
    <a href="${esc(door.ladder)}">What each rung costs, and what it buys &rarr;</a>
  </p>
  <p class="fd-note">${esc(NOT_AUTHORITY)}</p>
  <link rel="frontdoor" href="/.well-known/frontdoor.json">
</section>
`
if (args.has('--html')) write(cfg.htmlOut ?? 'build/frontdoor.html', htmlPartial)

// ── The React component ─────────────────────────────────────────────────────
// The same content, for the Next.js properties. Generated rather than
// hand-written so the two renderers can differ in syntax and never in content.
const reactComponent = `// Generated by scripts/emit-frontdoor.mjs from ${CFG}. Do not edit.
import door from '../../public/.well-known/frontdoor.json'

export function FrontDoor() {
  return (
    <section className="fd" aria-labelledby="fd-h">
      <h2 className="fd-h" id="fd-h">${JSON.stringify(cfg.voice ?? 'Reach us')}</h2>
      <ul className="fd-lanes">
        {door.lanes.map((l) => (
          <li className="fd-lane" key={l.id}>
            <span className="fd-lane-name">{l.id}</span>
            {l.question ? <span className="fd-lane-q">{l.question}</span> : null}
          </li>
        ))}
      </ul>
      <p className="fd-ladder">
        <a href={door.ladder}>What each rung costs, and what it buys &rarr;</a>
      </p>
      <p className="fd-note">{door.notAuthority}</p>
    </section>
  )
}
`
if (args.has('--react')) write(cfg.reactOut ?? 'src/components/FrontDoor.tsx', reactComponent)

console.log(`\n  ${door.property} — ${door.lanes.length} lane(s) · ${door.rungs.length} rung(s)${CHECK ? ' (check only)' : ''}\n`)
export { door, htmlPartial, reactComponent }
